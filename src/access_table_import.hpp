#pragma once

#include "csv.hpp"

#include <QSqlDatabase>
#include <QByteArray>
#include <QString>
#include <QStringList>
#include <QVector>
#include <optional>

namespace linaccess {
// Only scalar literal defaults; never evaluates a VBA or SQL expression.
std::optional<QString> accessLiteralDefaultSql(const QString& token);
struct AccessColumn {
    QString name;
    QString sqliteType;
    QString sourceType;
    bool required{};
    int primaryKeyOrder{};
    bool autoNumber{};
    QString sourceOrigin;
    int sourceSize{};
    bool hasDefault{};
    QString sourceDefault,sqlDefault;
    int sourcePrecision{},sourceScale{};
};

struct AccessIndex {
    QString name;
    QStringList columns;
    bool unique{};
    QVector<bool> descending; // Empty means the legacy all-ascending declaration.
};
struct AccessForeignKey {
    QStringList columns;
    QString parentTable;
    QStringList parentColumns;
    bool cascadeUpdate{};
    bool cascadeDelete{};
};
enum class AccessBinaryEncoding { Unsupported, MdbToolsHex };
// CSV is caller-owned data. NativeMdbBits reads the original source and verifies
// the selected numeric fields, including exact signed Currency ticks.
enum class AccessFloatingSource { Csv, NativeMdbBits };
// Strict unprefixed ASCII hex only; no guessing from arbitrary binary/text CSV.
QByteArray decodeMdbBinaryHex(std::string_view encoded);
struct AccessTableSchema {
    QVector<AccessColumn> columns;
    QVector<AccessIndex> indexes;
    QVector<AccessForeignKey> foreignKeys;
    QByteArray sourceIndexMetadata;
};
// Atomic full-database copy, including enforced relationships between copied tables.
// Existing tables are not overwritten; any failure rolls back the complete copy.
int importAccessDatabase(QSqlDatabase db, const QString& sourceFile);
AccessTableSchema parseMdbSchema(const QString& schema);
void importAccessTable(QSqlDatabase db, const QString& sourceFile,
                       const QString& tableName, const AccessTableSchema& schema,
                       const std::vector<std::vector<CsvField>>& data,
                       AccessBinaryEncoding binaryEncoding=AccessBinaryEncoding::Unsupported,
                       AccessFloatingSource floatingSource=AccessFloatingSource::Csv);

// Recognizes only simple column definitions generated by MDBTools, never
// executes SQL from an Access file. Returns empty on unknown or mismatched schema.
QVector<AccessColumn> parseMdbColumns(const QString& schema);

// Partial import: mapped types, NULLs, primary keys and exported indices.
// Use the full-database API for relationship metadata and enforcement.
// Exact Jet semantics/OLE rendering/round trips remain unsupported; raw BLOB
// bytes require explicit MDBTools hexadecimal export, never inferred CSV.
// Uses a separate SQLite transaction and never writes to the Access file.
void importAccessTable(QSqlDatabase db, const QString& sourceFile,
                       const QString& tableName,
                       const QVector<AccessColumn>& columns,
                       const std::vector<std::vector<CsvField>>& data,
                       AccessBinaryEncoding binaryEncoding=AccessBinaryEncoding::Unsupported,
                       AccessFloatingSource floatingSource=AccessFloatingSource::Csv);
}
